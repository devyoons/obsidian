--  DDL for View MEMBER_VIEW
--------------------------------------------------------

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "MESHOP"."MEMBER_VIEW" ("MEMBER_ID", "STORE_NAME", "MEMBER_NAME", "STORE_GRADE", "JOIN_DATE", "BOARD_COUNT") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  select m.member_id, m.store_name, m.member_name, m.store_grade, m.join_date, count(*) as board_count from member m inner join product p on (m.member_id = p.member_id) 
group by m.member_id, m.store_name, m.member_name, m.store_grade, m.join_date
;
