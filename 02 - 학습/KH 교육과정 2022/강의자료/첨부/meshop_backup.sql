  select c."NO",c."SELLER_ID",c."BUYER_ID",c."PRODUCT_ID",c."CREATE_DATE",c."CHECK_STATUS", p.title, m.store_name, m.member_id
    from chatroom c 
    join product p on(c.product_id = p.product_id) 
    left outer join member m on (c.seller_id = m.member_id) or (c.buyer_id = m.member_id)
